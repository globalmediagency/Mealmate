/**
 * The Zodiaque collection: the twelve animals of the Chinese zodiac, drawn
 * in pixel art (28 × 28 cells, four monochrome tones, see `../pixel.ts`)
 * in the spirit of the old handheld consoles. All of tier "moyen", with
 * the collection's own quotas (6 / 3 / 2 / 1). The grids are hand-drawn:
 * `.` empty, `0`–`3` tones (darkest first), `E` eye, `M` mouth.
 */
const PALETTE: SpeciesPalette = { primary: "#8f9270", secondary: "#5a5d44", accent: "#c6c8a2", eye: "#2a2c1f" };
/** Fallback parts (silhouette family) for code that still reads them; the pixels draw everything. */
const PARTS: SpeciesParts = { body: "round", ears: "round", eyes: "big", mouth: "smile", tail: "none", markings: "none", extra: null };

function zodiac(key: string, rarity: Rarity, name: string, tagline: string, signature: Species["signature"], pixel: PixelArt): Species {
  return { id: `moyen-zodiaque-${key}`, tier: "moyen", collection: "zodiaque", rarity, name, tagline, palette: PALETTE, parts: PARTS, anchors: pixelAnchors(pixel), signature, pixel };
}

